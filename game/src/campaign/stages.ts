/** 스테이지 수. `server.js` 의 `CAMPAIGN_STAGES` 와 같아야 한다. */
export const CAMPAIGN_STAGES = STAGES.length;

export function stageOf(n: number): Stage | null {
  return STAGES[n - 1] ?? null;
}

/** "2-3" 꼴. 장·판 모두 1부터. */
export function stageLabel(n: number): string {
  const c = Math.floor((n - 1) / STAGES_PER_CHAPTER) + 1;
  const i = ((n - 1) % STAGES_PER_CHAPTER) + 1;
  return `${c}-${i}`;
}

/**
 * 이 스테이지의 타워 배치. **부를 때마다 새 배열이다** — 시뮬레이션이 타워를 직접
 * 고쳐 쓰므로(병력·주인) 같은 배열을 두 판에 넘기면 두 번째 판이 앞 판의 끝에서 시작한다.
 *
 * `id` 는 배열 순서와 같아야 한다 (sim 이 `state.towers[id]` 로 찾는다).
 */
export function stageTowers(stage: Stage): Tower[] {
  return stage.spots.map(([x, y, owner, troops], id) => ({ id, x, y, owner, troops, relayCursor: 0 }));
}
