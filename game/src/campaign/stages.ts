import type { Tower } from '../sim/types';
import type { TowerKind } from '../towers';
import type { UnitKind } from '../units';

/** `[x, y, 주인, 시작 병력]`. 주인 1 = 사람, 2 = 봇, 0 = 중립. */
type Spot = readonly [x: number, y: number, owner: 0 | 1 | 2, troops: number];

export interface Stage {
  /** 1부터. 화면 표기 "2-3" 은 `stageLabel` 이 만든다. */
  readonly n: number;
  readonly botUnit: UnitKind;
  readonly botTower: TowerKind;
  /** 있으면 `botTower` 의 속도 대신 쓴다. 기본 타워보다 느리게 할 때만. */
  readonly botSpeed?: number;
  /** 처음 깼을 때 코인. `server.js` 의 `CAMPAIGN_FIRST_CLEAR` 와 같아야 한다. */
  readonly firstClear: number;
  readonly spots: readonly Spot[];
}

/** 한 장에 몇 판. 화면이 "장-판" 으로 적는다. */
export const STAGES_PER_CHAPTER = 5;

