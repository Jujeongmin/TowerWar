const DICTS: Record<Lang, Dict> = { en, ko, ja, zh, 'zh-Hant': zhHant, vi };

export function tx(key: Key, ...args: (string | number)[]): string {
  const d = DICTS[getLang()] ?? en;
  let s = d[key] ?? en[key];
  args.forEach((a, i) => {
    s = s.split(`{${i}}`).join(typeof a === 'number' ? a.toLocaleString() : a);
  });
  return s;
}

export function chapterName(c: number): string {
  return (tx('chapterNames').split('|')[c - 1] ?? tx('chapter', c));
}

/** 남은 ms → "3:05". */
export function mmss(ms: number): string {
  const s = Math.ceil(ms / 1000);
  return `${Math.floor(s / 60)}:${String(s % 60).padStart(2, '0')}`;
}

/** `data-tx="키"` 가 붙은 정적 글자를 지금 언어로 칠한다. 부팅과 언어 변경 때 부른다. */
export function applyTx(root: ParentNode = document): void {
  for (const el of Array.from(root.querySelectorAll<HTMLElement>('[data-tx]'))) {
    el.textContent = tx(el.dataset.tx as Key);
  }
}
